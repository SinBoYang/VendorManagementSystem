/*
  CSP_DB Schema (SQL Server)
*/

IF DB_ID(N'CSP_DB') IS NULL
BEGIN
	CREATE DATABASE CSP_DB;
END
GO

USE CSP_DB;
GO

CREATE TABLE dbo.CURRENCY
(
	CURRENCY_CODE NVARCHAR(10)  NOT NULL,
	CURRENCY_NAME NVARCHAR(50)  NOT NULL,
	EXCHANGE_RATE DECIMAL(18, 6) NOT NULL,
	CONSTRAINT PK_CURRENCY PRIMARY KEY (CURRENCY_CODE),
);
GO

CREATE TABLE dbo.BANK
(
	BANK_CODE NVARCHAR(20) NOT NULL,
	BANK_NAME NVARCHAR(100) NOT NULL,
	CONSTRAINT PK_BANK PRIMARY KEY (BANK_CODE)
);
GO

CREATE TABLE dbo.TAX
(
	TAX_CODE NVARCHAR(20) NOT NULL,
	TAX_PERCENT DECIMAL(5, 2) NOT NULL,
	CONSTRAINT PK_TAX PRIMARY KEY (TAX_CODE),
	CONSTRAINT CK_TAX_PERCENT CHECK (TAX_PERCENT >= 0 AND TAX_PERCENT <= 100)
);
GO

CREATE TABLE dbo.VENDOR
(
	VENDOR_ID BIGINT IDENTITY(1,1) NOT NULL,
	VENDOR_NAME NVARCHAR(100) NOT NULL,
	TAX_ID NVARCHAR(20) NOT NULL,
	STATUS NVARCHAR(20) NOT NULL,
	EMAIL NVARCHAR(200) NULL,
	PHONE NVARCHAR(30) NULL,
	ADDRESS NVARCHAR(300) NULL,
	BANK_CODE NVARCHAR(20) NULL,
	ACCOUNT_NAME NVARCHAR(100) NULL,
	ACCOUNT_NUMBER NVARCHAR(50) NULL,
	CURRENCY_CODE NVARCHAR(10) NULL,
	CONSTRAINT PK_VENDOR PRIMARY KEY (VENDOR_ID),
	CONSTRAINT FK_VENDOR_BANK FOREIGN KEY (BANK_CODE) REFERENCES dbo.BANK(BANK_CODE),
	CONSTRAINT FK_VENDOR_CURRENCY FOREIGN KEY (CURRENCY_CODE) REFERENCES dbo.CURRENCY(CURRENCY_CODE),
	CONSTRAINT CK_VENDOR_STATUS CHECK (STATUS IN (N'ACTIVE', N'INACTIVE'))
);
GO

CREATE TABLE dbo.INVOICE
(
	INVOICE_ID BIGINT IDENTITY(1,1) NOT NULL,
	INVOICE_NO NVARCHAR(30) NOT NULL,
	ITEM NVARCHAR(200) NOT NULL,
	CURRENCY_CODE NVARCHAR(10) NOT NULL,
	TAX_CODE NVARCHAR(20) NOT NULL,
	VENDOR_ID BIGINT NOT NULL,
	INVOICE_DATE DATE NOT NULL,
	DUE_DATE DATE NULL,
	REMARKS NVARCHAR(500) NULL,
	STATUS NVARCHAR(20) NOT NULL CONSTRAINT DF_INVOICE_STATUS DEFAULT (N'DRAFT'),
	SUBTOTAL DECIMAL(18,2) NOT NULL CONSTRAINT DF_INVOICE_SUBTOTAL DEFAULT (0),
	TOTAL DECIMAL(18,2) NOT NULL CONSTRAINT DF_INVOICE_TOTAL DEFAULT (0),
	CREATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_INVOICE_CREATED_AT DEFAULT (SYSDATETIME()),
	UPDATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_INVOICE_UPDATED_AT DEFAULT (SYSDATETIME()),

	CONSTRAINT PK_INVOICE PRIMARY KEY (INVOICE_ID),
	CONSTRAINT UQ_INVOICE_NO UNIQUE (INVOICE_NO),
	CONSTRAINT FK_INVOICE_VENDOR FOREIGN KEY (VENDOR_ID) REFERENCES dbo.VENDOR(VENDOR_ID),
	CONSTRAINT FK_INVOICE_CURRENCY FOREIGN KEY (CURRENCY_CODE) REFERENCES dbo.CURRENCY(CURRENCY_CODE),
	CONSTRAINT FK_INVOICE_TAX FOREIGN KEY (TAX_CODE) REFERENCES dbo.TAX(TAX_CODE),
	CONSTRAINT CK_INVOICE_STATUS CHECK (STATUS IN (N'DRAFT', N'SUBMITTED', N'APPROVED', N'REJECTED', N'DELETED')),
);
GO

CREATE TABLE dbo.PAYMENT
(
	PAYMENT_ID BIGINT IDENTITY(1,1) NOT NULL,
	INVOICE_ID BIGINT NOT NULL,
	PAYER_REMARK NVARCHAR(500) NULL,
	PAYMENTDATE DATE NOT NULL,
	CONSTRAINT PK_PAYMENT PRIMARY KEY (PAYMENT_ID),
	CONSTRAINT FK_PAYMENT_INVOICE FOREIGN KEY (INVOICE_ID) REFERENCES dbo.INVOICE(INVOICE_ID),
	CONSTRAINT UQ_PAYMENT_INVOICE_ID UNIQUE (INVOICE_ID)
);
GO


